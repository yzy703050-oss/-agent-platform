CREATE TABLE travel.threads(id text PRIMARY KEY,
 user_id text NOT NULL,
 conversation_id text NOT NULL,
 origin_service text NOT NULL DEFAULT 'platform',
 origin_thread_id text NOT NULL,
 agent_kind text NOT NULL DEFAULT 'travel' CHECK(agent_kind='travel'),
 thread_role text NOT NULL DEFAULT 'plan_work' CHECK(thread_role='plan_work'),
 context_epoch bigint NOT NULL DEFAULT 1 CHECK(context_epoch>0),
 summary jsonb,
 summary_through_ordinal bigint NOT NULL DEFAULT 0 CHECK(summary_through_ordinal>=0),
 summary_version bigint NOT NULL DEFAULT 0 CHECK(summary_version>=0),
 last_main_context_ordinal bigint NOT NULL DEFAULT 0 CHECK(last_main_context_ordinal>=0),
 last_main_context_epoch bigint NOT NULL CHECK(last_main_context_epoch>0),
 next_message_ordinal bigint NOT NULL DEFAULT 1 CHECK(next_message_ordinal>0),
 UNIQUE(id,user_id,conversation_id));
CREATE TABLE travel.tasks(
 id text PRIMARY KEY,
 caller_id text NOT NULL,
 subject_id text NOT NULL,
 conversation_id text NOT NULL,
 source_run_id text NOT NULL,
 delegation_id text NOT NULL,
 request_key text NOT NULL,
 input_hash text NOT NULL,
 arguments jsonb NOT NULL CHECK(jsonb_typeof(arguments)='object'),
 scope_id text NOT NULL,
 scope_hash text NOT NULL,
 thread_id text,

 status text NOT NULL CHECK(status IN('queued','running','succeeded','failed','timed_out','interrupted')),
 worker_id text,
 lease_epoch bigint NOT NULL DEFAULT 0 CHECK(lease_epoch>=0),
 lease_expires_at timestamptz,
 retry_count integer NOT NULL DEFAULT 0 CHECK(retry_count BETWEEN 0 AND 3),
 checkpoint_version bigint NOT NULL DEFAULT 0 CHECK(checkpoint_version>=0),
 deadline_at timestamptz NOT NULL,
 not_before timestamptz NOT NULL DEFAULT clock_timestamp(),
 loop_count integer NOT NULL DEFAULT 0 CHECK(loop_count BETWEEN 0 AND 8),
 no_progress_count integer NOT NULL DEFAULT 0 CHECK(no_progress_count BETWEEN 0 AND 2),
 result_version bigint NOT NULL DEFAULT 0 CHECK(result_version>=0),
 result jsonb,
 error jsonb,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 completed_at timestamptz,

 UNIQUE(id,subject_id,conversation_id),
 UNIQUE(caller_id,subject_id,request_key),
 FOREIGN KEY(thread_id,subject_id,conversation_id) REFERENCES travel.threads(id,user_id,conversation_id),
 CHECK((status='running' AND worker_id IS NOT NULL AND lease_expires_at IS NOT NULL AND lease_epoch>0) OR (status<>'running' AND worker_id IS NULL AND lease_expires_at IS NULL)),
 CHECK(lease_expires_at<=deadline_at),
 CHECK(deadline_at>created_at)
);
CREATE UNIQUE INDEX one_active_thread_task ON travel.tasks(thread_id) WHERE status IN('queued',
 'running');
CREATE INDEX travel_task_leases ON travel.tasks(status,
 lease_expires_at,
 deadline_at) WHERE status IN('queued',
 'running');
CREATE INDEX travel_task_due ON travel.tasks(not_before,
 id) WHERE status='queued';
