CREATE FUNCTION travel.reject_fact_mutation() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $$ BEGIN RAISE EXCEPTION 'immutable runtime fact' USING ERRCODE='23514'; END $$;
CREATE TRIGGER immutable_evidence BEFORE UPDATE OR DELETE ON travel.tool_evidence FOR EACH ROW EXECUTE FUNCTION travel.reject_fact_mutation();
CREATE TRIGGER immutable_import BEFORE UPDATE OR DELETE ON travel.evidence_imports FOR EACH ROW EXECUTE FUNCTION travel.reject_fact_mutation();
CREATE TRIGGER immutable_checkpoint BEFORE UPDATE OR DELETE ON travel.checkpoints FOR EACH ROW EXECUTE FUNCTION travel.reject_fact_mutation();
CREATE TRIGGER immutable_revision BEFORE UPDATE OR DELETE ON travel.revisions FOR EACH ROW EXECUTE FUNCTION travel.reject_fact_mutation();
