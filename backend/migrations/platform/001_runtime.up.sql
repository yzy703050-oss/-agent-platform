 thread_id text,
 context_epoch bigint CHECK(context_epoch>0),
 source_run_id text,
 tool_call_id text,
 decision_key text,
 kind text NOT NULL CHECK(kind IN('review_only','explicit_write','periodic_summary','explicit_reanalysis')),
 request_hash text NOT NULL,
 arguments jsonb NOT NULL CHECK(jsonb_typeof(arguments)='object'),
 review_from_round bigint,
 review_through_round bigint,
 from_round bigint,
 through_round bigint,
 base_memory_revision bigint NOT NULL CHECK(base_memory_revision>=0),
 status text NOT NULL CHECK(status IN('accepted','running','succeeded','failed','unknown')),
 worker_id text,
 lease_expires_at timestamptz,
 lease_epoch bigint NOT NULL DEFAULT 0 CHECK(lease_epoch>=0),
