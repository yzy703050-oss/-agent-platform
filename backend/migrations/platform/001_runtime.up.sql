 FOREIGN KEY(conversation_id,user_id) REFERENCES platform.conversations(id,user_id),
 CHECK(id=conversation_id AND parent_thread_id IS NULL),
 CHECK(0<=memory_summarized_through_round AND memory_summarized_through_round<=memory_reviewed_through_round AND memory_reviewed_through_round<memory_next_round_no)
