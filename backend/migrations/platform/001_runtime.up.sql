CREATE FUNCTION platform.reject_fact_mutation() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $$ BEGIN RAISE EXCEPTION 'immutable runtime fact' USING ERRCODE='23514'; END $$;
CREATE TRIGGER immutable_evidence BEFORE UPDATE OR DELETE ON platform.tool_evidence FOR EACH ROW EXECUTE FUNCTION platform.reject_fact_mutation();
CREATE TRIGGER immutable_import BEFORE UPDATE OR DELETE ON platform.evidence_imports FOR EACH ROW EXECUTE FUNCTION platform.reject_fact_mutation();
CREATE TRIGGER immutable_checkpoint BEFORE UPDATE OR DELETE ON platform.checkpoints FOR EACH ROW EXECUTE FUNCTION platform.reject_fact_mutation();
CREATE TRIGGER immutable_memory BEFORE UPDATE OR DELETE ON platform.user_memory_revisions FOR EACH ROW EXECUTE FUNCTION platform.reject_fact_mutation();
